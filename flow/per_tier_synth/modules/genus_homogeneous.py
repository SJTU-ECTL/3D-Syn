def prepare_genus_inputs(wrapper_design, wrapper_plan):
    os.makedirs(GENUS_TMP_DIR, exist_ok=True)
    os.makedirs(GENUS_REPORT_DIR, exist_ok=True)
    os.makedirs(GENUS_DB_DIR, exist_ok=True)
